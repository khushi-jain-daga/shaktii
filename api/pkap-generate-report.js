function buildDynamicReport(data) {
  const fileName = data?.fileName || 'Uploaded Log File';
  const metadata = data?.metadata || {};
  const riskScore = Number(metadata.overallRiskScore || 0);
  const riskLevel = riskScore >= 75 ? 'CRITICAL' : riskScore >= 50 ? 'HIGH' : riskScore >= 25 ? 'MEDIUM' : 'LOW';
  const severity = data?.severityBreakdown || { critical: 0, high: 0, medium: 0, low: 0, info: 0 };
  const findings = Array.isArray(data?.findings) ? data.findings : [];
  const iocs = Array.isArray(data?.iocs) ? data.iocs : [];
  const remediation = Array.isArray(data?.remediationChecklist) ? data.remediationChecklist : [];
  const fileHash = Math.abs(fileName.split('').reduce((acc, char) => acc + char.charCodeAt(0), 0) % 9000 + 1000);
  const ticketId = `SEC-${new Date().getFullYear()}-${fileHash}`;
  let md = `# SECURITY INCIDENT INVESTIGATION REPORT\n\n`;
  md += `*Pkap Analyzer Log Security Analysis & Forensic Investigation Report*\n\n`;
  md += `**Target Log File:** ${fileName}\n`;
  md += `**Case / Ticket ID:** ${ticketId}\n`;
  md += `**Date of Report:** ${new Date().toLocaleDateString('en-GB', { day: 'numeric', month: 'short', year: 'numeric' })}\n`;
  md += `**Log Format Detected:** ${metadata.logTypeDetected || 'Unknown'}\n`;
  md += `**Time Period Covered:** ${metadata.timeRangeCovered || 'N/A'}\n`;
  md += `**Overall Risk Score:** ${riskScore} / 100 (${riskLevel} RISK)\n\n---\n\n`;
  md += `## 1. Executive Summary\n${data?.executiveSummary || 'Analysis completed.'}\n\n`;
  md += `## 2. Risk Assessment & Severity Breakdown\n| Severity | Count | Context |\n| --- | ---: | --- |\n`;
  md += `| Critical | ${severity.critical || 0} | Immediate threat / breach signal |\n| High | ${severity.high || 0} | Severe anomaly / unauthorized activity |\n| Medium | ${severity.medium || 0} | Suspicious event / warning |\n| Low | ${severity.low || 0} | Minor deviation |\n| Info | ${severity.info || 0} | Baseline event |\n\n`;
  md += `## 3. Detailed Security Findings & Log Events\n`;
  if (findings.length) {
    md += `| Severity | Event Type | Source | Timestamp | Description |\n| --- | --- | --- | --- | --- |\n`;
    findings.slice(0, 25).forEach((f) => {
      md += `| ${f.severity || 'Info'} | ${f.eventType || 'Event'} | ${f.sourceIP || 'N/A'} | ${f.timestamp || '-'} | ${String(f.description || '').replace(/\|/g, '\\|').replace(/\n/g, ' ')} |\n`;
    });
    md += `\n`;
    const evidence = findings.filter((f) => ['Critical', 'High'].includes(f.severity) && f.rawLogSnippet).slice(0, 5);
    if (evidence.length) {
      md += `### 3.1 Raw Evidence Snippets\n`;
      evidence.forEach((f, i) => {
        md += `**Snippet #${i + 1} (${f.severity} - ${f.eventType}):**\n\n`;
        md += '```text\n' + String(f.rawLogSnippet).trim() + '\n```\n\n';
      });
    }
  } else md += `No high-severity anomalies were identified.\n\n`;
  md += `## 4. Indicators of Compromise (IOCs)\n`;
  if (iocs.length) {
    md += `| Indicator | Type | Reputation |\n| --- | --- | --- |\n`;
    iocs.forEach((ioc) => { md += `| \`${ioc.value || 'Unknown'}\` | ${ioc.type || 'Unknown'} | ${ioc.reputation || 'Unknown'} |\n`; });
    md += `\n`;
  } else md += `No specific IOCs were extracted.\n\n`;
  md += `## 5. Remediation & Recommended Actions\n`;
  (remediation.length ? remediation : ['Continue monitoring and maintain security baselines.']).forEach((item, i) => { md += `${i + 1}. ${item}\n`; });
  md += `\n## 6. Conclusion\n${riskScore >= 60 ? 'Immediate analyst review and containment of confirmed malicious indicators are recommended.' : 'No immediate lockdown is indicated; continue monitoring and correlation.'}\n\n---\n**Report Generated By:** SHAKTII / Pkap Analyzer\n`;
  return md;
}

export default async function handler(req, res) {
  if (req.method !== 'POST') return res.status(405).json({ success: false, error: 'Method not allowed' });
  const analysisData = req.body?.analysisData;
  if (!analysisData) return res.status(400).json({ success: false, error: 'analysisData is required' });
  const fallback = buildDynamicReport(analysisData);

  if (!process.env.GEMINI_API_KEY) return res.status(200).json({ success: true, report: fallback, providerUsed: 'Local report builder' });
  const prompt = `You are a Tier 3 Security Operations Center lead analyst. Generate a formal Markdown incident report using ONLY the supplied facts. Include Executive Summary, Incident Overview, Severity Breakdown, Timeline/Findings, Technical Evidence, IOCs, Impact Assessment, Remediation, and Conclusion. Do not invent compromise or attribution.\n\nAnalysis JSON:\n${JSON.stringify(analysisData).slice(0, 30000)}`;
  try {
    const endpoint = `https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash:generateContent?key=${encodeURIComponent(process.env.GEMINI_API_KEY)}`;
    const response = await fetch(endpoint, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ contents: [{ parts: [{ text: prompt }] }], generationConfig: { temperature: 0.1 } }) });
    if (!response.ok) return res.status(200).json({ success: true, report: fallback, providerUsed: 'Local report builder' });
    const payload = await response.json();
    const report = payload?.candidates?.[0]?.content?.parts?.[0]?.text?.trim();
    return res.status(200).json({ success: true, report: report && report.length > 100 ? report : fallback, providerUsed: report ? 'Gemini' : 'Local report builder' });
  } catch {
    return res.status(200).json({ success: true, report: fallback, providerUsed: 'Local report builder' });
  }
}
